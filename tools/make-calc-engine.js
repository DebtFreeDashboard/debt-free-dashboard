#!/usr/bin/env node
/* make-calc-engine.js — builds calculators/assets/engine.js from app/dashboard.html
 *
 * The calculator pages must never disagree with the dashboard. Rather than
 * re-implement the payoff math (and drift), this copies the dashboard's own
 * engine functions VERBATIM into a standalone script. Re-run after any change
 * to the engine in dashboard.html:
 *
 *     node tools/make-calc-engine.js
 *
 * tools/test-calculators.js checks that the copied functions are byte-identical
 * to the live ones, so a stale engine fails the test run instead of shipping.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'app', 'dashboard.html');
const OUT = path.join(ROOT, 'calculators', 'assets', 'engine.js');

// Top-level functions copied from the dashboard, in dependency order.
const FUNCS = [
  '_monthDelta', 'planMonthIndex', 'promoSwitchIndex', 'planMonthDate', 'planMonthsAway',
  'minPaymentFloors', 'minDueFor',
  'computePassiveInterestCost', 'estimatePassiveHorizon', 'avalancheRateAt', 'avalancheSort',
  'simulate',
  '_permute', '_scoreOrder', '_seedOrders',
  'estimateMinPayment', 'inferLoanType'
];
const CONSTS = ['OPTIMIZED_EXHAUSTIVE_LIMIT'];

function extractFunction(lines, name) {
  const start = lines.findIndex(l => l.startsWith('function ' + name + '('));
  if (start < 0) throw new Error('make-calc-engine: function ' + name + ' not found in dashboard.html');
  const first = lines[start];
  const opens = (first.match(/{/g) || []).length, closes = (first.match(/}/g) || []).length;
  if (opens > 0 && opens === closes) return first;            // one-liner
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i] === '}') return lines.slice(start, i + 1).join('\n');
    if (/^function /.test(lines[i])) break;                     // ran into the next function
  }
  throw new Error('make-calc-engine: could not find the end of ' + name);
}
function extractConst(lines, name) {
  const l = lines.find(x => x.startsWith('const ' + name + ' ='));
  if (!l) throw new Error('make-calc-engine: const ' + name + ' not found');
  return l;
}

function build() {
  const html = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');
  const lines = html.split('\n');
  const ver = (html.match(/APP_VERSION = '([^']+)'/) || [])[1];
  if (!ver) throw new Error('make-calc-engine: APP_VERSION not found');
  const parts = FUNCS.map(n => extractFunction(lines, n));
  const consts = CONSTS.map(n => extractConst(lines, n));

  const body = `/* GENERATED by tools/make-calc-engine.js from app/dashboard.html v${ver}.
 * Do not edit by hand: change the engine in dashboard.html and regenerate.
 * Every function between the COPIED markers is byte-identical to the app's. */
(function (global) {
'use strict';
// The app reads these globals; the calculators never use the ledger, so they
// are inert here (every call goes through run(), which sets anchor:false).
var strategy = 'avalanche';
function currentMonthLedger() { return { paid: {}, accrued: {} }; }
function _netMonthOne() { return { minCovered: {}, extraAlreadyPaid: 0 }; }

// ---- COPIED FROM dashboard.html (begin) ----
${consts.join('\n')}
${parts.join('\n\n')}
// ---- COPIED FROM dashboard.html (end) ----

// Calculator entry point. strat: 'avalanche' | 'snowball' | 'hybrid' (array order).
function run(debts, extra, strat, opts) {
  var o = Object.assign({ anchor: false }, opts || {});
  o.anchor = false;
  return simulate(debts.map(function (d) { return Object.assign({}, d); }), extra || 0, 0, strat, null, o);
}

// Same search the dashboard's Optimized strategy runs (computeOptimizedOrder),
// over the calculator's debts instead of the app's stored ones.
function optimizedOrder(targets, extra) {
  if (!targets || targets.length < 2) return null;
  var ids = targets.map(function (d) { return d.id; });
  var best = null, considered = 0;
  var score = function (order) {
    var arranged = order.map(function (id) { return targets.find(function (d) { return d.id === id; }); });
    return run(arranged, extra, 'hybrid');
  };
  var consider = function (order) {
    var r = score(order); considered++;
    if (r && !r.diverged && (!best || r.totalInterest < best.interest - 1e-9)) {
      best = { order: order.slice(), interest: r.totalInterest, months: r.months };
      return true;
    }
    return false;
  };
  if (targets.length <= OPTIMIZED_EXHAUSTIVE_LIMIT) {
    _permute(ids).forEach(consider);
    return best ? { order: best.order, interest: best.interest, months: best.months, exhaustive: true, considered: considered } : null;
  }
  _seedOrders(targets).forEach(consider);
  if (!best) return null;
  var improved = true, guard = 0;
  while (improved && guard++ < 12 && considered < 4000) {
    improved = false;
    for (var i = 0; i < best.order.length - 1 && considered < 4000; i++) {
      for (var j = i + 1; j < best.order.length && considered < 4000; j++) {
        var cand = best.order.slice(); var t = cand[i]; cand[i] = cand[j]; cand[j] = t;
        if (consider(cand)) improved = true;
      }
    }
  }
  return { order: best.order, interest: best.interest, months: best.months, exhaustive: false, considered: considered };
}

// The debt that receives extra money in month 1 under a strategy.
function firstTarget(debts, strat) {
  var c = debts.filter(function (d) { return d.balance > 0; }).map(function (d) { return Object.assign({}, d); });
  if (strat === 'avalanche') avalancheSort(c, null, null, 1);
  else if (strat === 'snowball') c.sort(function (a, b) { return a.balance - b.balance; });
  return c[0] || null;
}

global.DFEngine = {
  firstTarget: firstTarget,
  version: '${ver}',
  run: run,
  optimizedOrder: optimizedOrder,
  minPaymentFloors: minPaymentFloors,
  estimateMinPayment: estimateMinPayment,
  inferLoanType: inferLoanType,
  planMonthDate: planMonthDate,
  planMonthsAway: planMonthsAway,
  _copied: ${JSON.stringify(FUNCS.concat(CONSTS))}
};
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  return { out: OUT, version: ver, functions: FUNCS.length };
}

module.exports = { build, extractFunction, FUNCS, CONSTS, SRC };
if (require.main === module) {
  const r = build();
  console.log('wrote ' + path.relative(ROOT, r.out) + ' (engine from v' + r.version + ', ' + r.functions + ' functions)');
}
